@router.post("/generate-and-save")
async def generate_and_save_prd(
    workspace_id: str,
    request: PRDGenerationRequest,
    current_user: User = Depends(get_current_user),
    session: Session = Depends(get_session)
):
    """
    Generate PRD and automatically save it to the workspace
    Combines generation and creation in one operation
    """
    task_id = str(uuid4())

    logger.info(f"Starting generate-and-save for workspace {workspace_id}")

    try:
        # Generate PRD content
        generation_response = await generate_prd_sync(request, current_user)

        if generation_response.status != "completed" or not generation_response.generated_content:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="PRD generation failed"
            )

        # Create PRD in workspace
        from gtplanner.web.services.prd_service import prd_service

        # Generate a title from the description
        title = request.description.split('.')[0][:100]  # First sentence, max 100 chars

        prd = prd_service.create_prd(
            session=session,
            workspace_id=workspace_id,
            title=title,
            content=generation_response.generated_content,
            created_by=current_user.id
        )

        logger.info(f"PRD created successfully: {prd.id}")

        return {
            "task_id": task_id,
            "status": "completed",
            "message": "PRD generated and saved successfully",
            "prd_id": prd.id,
            "prd_title": prd.title,
            "prd_version": prd.version
        }

    except Exception as e:
        logger.error(f"Error in generate-and-save: {str(e)}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate and save PRD: {str(e)}"
        )