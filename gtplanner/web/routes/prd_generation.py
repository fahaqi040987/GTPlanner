"""
PRD Generation routes - integrates GTPlanner AI generation with web interface
"""

from fastapi import APIRouter, Depends, HTTPException, status
from sqlmodel import Session
from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional
from uuid import uuid4
import logging

from gtplanner.web.database import get_session
from gtplanner.web.middleware import get_current_user
from gtplanner.web.models import User

logger = logging.getLogger(__name__)

router = APIRouter()


class PRDGenerationRequest(BaseModel):
    """Request for generating PRD from description"""
    description: str = Field(..., min_length=10, max_length=5000, description="Natural language description of the product requirements")
    language: str = Field(default="en", description="Language for generated PRD (en, zh, ja, es, fr, id)")
    context: Optional[str] = Field(None, max_length=2000, description="Additional context for PRD generation")


class PRDGenerationResponse(BaseModel):
    """Response from PRD generation"""
    task_id: str
    status: str
    message: str
    generated_content: Optional[Dict[str, Any]] = None


